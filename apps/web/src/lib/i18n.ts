/**
 * Voltade i18n — two locales, zero dependencies.
 *
 * WHY NOT next-intl / next-i18next: the portal ships exactly two locales and every
 * string is known at build time. A dictionary object plus three helpers does the job
 * without adding a runtime, a provider tree, or a message-loading waterfall — the same
 * reasoning as the hand-rolled admin charts.
 *
 * WHY URL LOCALES (/ar/…, /en/…) AND NOT A COOKIE TOGGLE: each language must be its own
 * crawlable URL with its own canonical and hreflang cluster. A cookie-switched single
 * URL set is invisible to Google in the other language — exactly the competitor weakness
 * this portal is built to beat. The cookie (`voltade_locale`) only chooses the redirect
 * target for *unprefixed* URLs; every rendered page lives under its locale.
 *
 * DATA FALLBACK: rows carry `titleEn`/`nameEn` where the schema has them. `pick()`
 * returns the English field when present and falls back to Arabic, so an untranslated
 * game never renders an empty card — it renders its Arabic name on the English site,
 * which is what every major portal does for imported content.
 */

export const LOCALES = ['ar', 'en'] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = 'ar';
export const LOCALE_COOKIE = 'voltade_locale';

export function isLocale(value: string | undefined | null): value is Locale {
  return value === 'ar' || value === 'en';
}

export function dirFor(locale: Locale): 'rtl' | 'ltr' {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

/** Prefixes an internal path with the locale: l('en', '/games') → '/en/games'. */
export function l(locale: Locale, path: string): string {
  if (path.startsWith('http') || path.startsWith('//')) return path;
  const clean = path.startsWith('/') ? path : `/${path}`;
  return `/${locale}${clean === '/' ? '' : clean}`;
}

/** Number formatting per locale — Arabic-Indic digits stay on the Arabic side. */
const numberFormats = new Map<Locale, Intl.NumberFormat>();
export function nf(locale: Locale): Intl.NumberFormat {
  let format = numberFormats.get(locale);
  if (!format) {
    format = new Intl.NumberFormat(locale === 'en' ? 'en-US' : 'ar-EG');
    numberFormats.set(locale, format);
  }
  return format;
}
export function n(locale: Locale, value: number | null | undefined): string {
  return nf(locale).format(value ?? 0);
}

/** Compact variant for tiles and rails: ١٢٫٣ ألف / 12.3K instead of five digits. */
const compactFormats = new Map<Locale, Intl.NumberFormat>();
export function nfc(locale: Locale): Intl.NumberFormat {
  let format = compactFormats.get(locale);
  if (!format) {
    format = new Intl.NumberFormat(locale === 'en' ? 'en-US' : 'ar-EG', { notation: 'compact', maximumFractionDigits: 1 });
    compactFormats.set(locale, format);
  }
  return format;
}
export function dateLocale(locale: Locale): string {
  return locale === 'en' ? 'en-US' : 'ar-EG';
}

/** English field when the visitor reads English and the row has one; Arabic otherwise. */
export function pick(locale: Locale, ar: string | null | undefined, en?: string | null | undefined): string {
  if (locale === 'en' && en && en.trim()) return en;
  return ar ?? '';
}

