const dictionaries: Record<Locale, Record<MessageKey, string>> = { ar, en };

/** t('en', 'game.playFree', { title: 'Volt 2048' }) → 'Play Volt 2048 free' */
export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text: string = dictionaries[locale][key] ?? dictionaries.ar[key] ?? String(key);
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

/** The hreflang cluster every page attaches: both locales plus x-default. */
export function localeAlternates(locale: Locale, path: string): { canonical: string; languages: Record<string, string> } {
  return {
    canonical: l(locale, path),
    languages: { ar: l('ar', path), en: l('en', path), 'x-default': l(DEFAULT_LOCALE, path) },
  };
}
